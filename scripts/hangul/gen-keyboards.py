#!/usr/bin/env python3
# NickelOS: turns libhangul's keyboard layouts (its data/keyboards) into
# nickel-hangul-keyboards.js for the Hangul input method's JavaScript engine
# (patches/app-i18n/chromeos-hangul).
#   gen-keyboards.py LIBHANGUL/data/keyboards OUT.js
import re, sys
D = sys.argv[1]
def combos(text):
    out = {}
    for m in re.finditer(r'<include file="([^"]+)"/>', text):
        out.update(combos(open(f"{D}/{m.group(1)}").read()))
    for m in re.finditer(r'<item first="0x([0-9a-f]+)" second="0x([0-9a-f]+)" result="0x([0-9a-f]+)"', text):
        out[(int(m.group(1), 16), int(m.group(2), 16))] = int(m.group(3), 16)
    return out
def esc(c):
    return "\\u%04X" % c
lines = []
for kid in ["2", "39", "3f", "3s", "ahn", "ro"]:
    text = open(f"{D}/hangul-keyboard-{kid}.xml.template").read()
    ktype = re.search(r'type="([^"]+)"', text).group(1)
    m0 = text.split('<map id="0">')[1].split("</map>")[0]
    keys = {int(k, 16): int(v, 16) for k, v in re.findall(r'<item key="0x([0-9a-f]+)" value="0x([0-9a-f]+)"', m0)}
    # Keys whose value is the key itself are left out: they type as they are.
    keys = {k: v for k, v in keys.items() if v != k}
    keystr = "".join(esc(k) for k in sorted(keys))
    valstr = "".join(esc(keys[k]) for k in sorted(keys))
    comb = combos(text)
    combstr = "".join(esc(a) + esc(b) + esc(r) for (a, b), r in sorted(comb.items()))
    lines.append((kid, ktype, keystr, valstr, combstr))
def wrap(s, indent="        ", width=78):
    chunks, step = [], (width - len(indent) - 4) // 6 * 6
    for i in range(0, len(s), step):
        chunks.append(indent + "'" + s[i:i+step] + "'")
    return " +\n".join(chunks)
out = ["// NickelOS: libhangul's keyboard layouts (data/keyboards/*.xml), for",
       "// nickel-hangul.js; generated by gen-keyboards.py. libhangul is",
       "// Copyright (C) 2006-2011 Choe Hwanjin and licensed under the GNU LGPL",
       "// 2.1 or later; these tables are its data. ASCII only: the page declares",
       "// no charset.",
       "//",
       "// Each layout: its type (libhangul's: jaso is a 3-set layout, whose keys",
       "// name initial, medial or final jamo; romaja spells), the keys it maps",
       "// and their jamo, one to one, and the combinations, three code points",
       "// each: first, second and their result. Unicode conjoining jamo.",
       "",
       "'use strict';",
       "",
       "var NICKEL_HANGUL_KEYBOARDS = {"]
for kid, ktype, keystr, valstr, combstr in lines:
    out.append(f"  '{kid}': {{")
    out.append(f"    type: '{ktype}',")
    out.append(f"    keys:\n" + wrap(keystr) + ",")
    out.append(f"    values:\n" + wrap(valstr) + ",")
    out.append(f"    combinations:\n" + wrap(combstr) + ",")
    out.append("  },")
out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
