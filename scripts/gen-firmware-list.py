#!/usr/bin/env python3
"""Regenerate sys-kernel/linux-firmware-nickel: file list, LICENSE, license texts.

Run on the build host after `setup_board --board=nickel` and after emerging
sys-kernel/linux-firmware and sys-firmware/sof-firmware for the board, and
again whenever LINUX_FIRMWARE in profiles/base/make.defaults changes or the
ebuild moves to a new upstream release.

  gen-firmware-list.py <flex-firmware-list> <upstream-src-dir> <board-sysroot> <src-root>

flex-firmware-list: one path per line, relative to /lib/firmware, taken from a
    ChromeOS Flex image (find lib/firmware on its ROOT-A). Only the names are
    used, as the selection of hardware to support.
upstream-src-dir: the extracted linux-firmware-<PV> tarball the ebuild uses.
board-sysroot: e.g. /srv/nickel/src/out/build/nickel
src-root: the ChromiumOS source root (for the existing license directories),
    e.g. /srv/nickel/src

Writes:
    sys-kernel/linux-firmware-nickel/files/firmware.list
    the LICENSE block of the ebuild (between the GENERATED markers)
    licenses/<name> for licenses the tree does not already carry
"""
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile

flex_list, upstream, sysroot, src_root = sys.argv[1:5]
overlay = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
pkgdir = os.path.join(overlay, "sys-kernel", "linux-firmware-nickel")
ebuild = sorted(glob.glob(os.path.join(pkgdir, "linux-firmware-nickel-*.ebuild")))[-1]

# Stage exactly the way the ebuild does, so WHENCE "Link:" entries exist.
stage = tempfile.mkdtemp(prefix="lfw-stage-")
subprocess.run([os.path.join(upstream, "copy-firmware.sh"), stage], cwd=upstream,
               check=True, stdout=subprocess.DEVNULL)

# 1. Selection: Flex's set minus what the board's own packages install, minus
#    what upstream does not carry, closed over symlinks.
want = [l.rstrip("\n") for l in open(flex_list) if l.strip()]
owned = set()
for pkg in ("sys-kernel/linux-firmware-", "sys-firmware/sof-firmware-",
            "net-wireless/wireless-regdb-"):
    for contents in glob.glob(os.path.join(sysroot, "var/db/pkg", pkg + "*", "CONTENTS")):
        for line in open(contents):
            kind, _, rest = line.partition(" ")
            if kind in ("obj", "sym") and rest.startswith("/lib/firmware/"):
                # CONTENTS: "obj <path> <md5> <mtime>" / "sym <path> -> <tgt> <mtime>"
                path = rest.rsplit(" ", 2)[0] if kind == "obj" else rest.split(" -> ")[0]
                owned.add(path[len("/lib/firmware/"):])
if not any(o for o in owned):
    sys.exit(f"no firmware package CONTENTS under {sysroot}; emerge them first")

present = lambda p: os.path.lexists(os.path.join(stage, p))
sel, missing = set(), []
for p in want:
    if p in owned:
        continue
    (sel.add(p) if present(p) else missing.append(p))
changed = True
while changed:
    changed = False
    for p in list(sel):
        full = os.path.join(stage, p)
        if os.path.islink(full):
            t = os.path.normpath(os.path.join(os.path.dirname(p), os.readlink(full)))
            if t not in sel and t not in owned:
                if not present(t):
                    sys.exit(f"link {p} -> {t}: target missing upstream")
                sel.add(t)
                changed = True

with open(os.path.join(pkgdir, "files", "firmware.list"), "w") as f:
    f.write("# Generated by scripts/gen-firmware-list.py. Do not edit by hand.\n")
    f.write("\n".join(sorted(sel)) + "\n")

# 2. Licenses, from WHENCE. Each "Driver:" block lists File/RawFile/Link lines
#    and Licence/License lines; every license a block names is applied to every
#    file in it. That over-attributes in a few mixed blocks, which only adds
#    license texts to the credits page, never drops one.
SEP = re.compile(r"^-{10,}\s*$")
REF = re.compile(r"\b(LICEN[CS]E\.[\w.+-]+|GPL-[23]\.0[\w+-]*|Apache-2\.0|MIT)\b")
file_lics, files, lics = {}, [], set()


def flush():
    global files, lics
    for f in files:
        file_lics.setdefault(f, set()).update(lics)
    files, lics = [], set()


for line in open(os.path.join(upstream, "WHENCE"), errors="replace"):
    if SEP.match(line):
        flush()
        continue
    m = re.match(r"^(?:File|RawFile|Link):\s*(.+?)\s*(?:->.*)?$", line)
    if m:
        files.append(m.group(1).strip().strip('"'))
        continue
    if re.match(r"^Licen[cs]e:", line):
        lics.update(REF.findall(line))
flush()

# Map upstream names to the names license directories already use.
RENAME = {"GPL-2.0": "GPL-2", "GPL-2.0-only": "GPL-2", "GPL-2.0-or-later": "GPL-2+",
          "GPL-3.0": "GPL-3", "GPL-3.0-only": "GPL-3", "Apache-2.0": "Apache-2.0"}
needed, unlicensed = set(), []
for p in sel:
    names = file_lics.get(p)
    if not names:
        unlicensed.append(p)
        continue
    needed.update(RENAME.get(n, n) for n in names)
# Files WHENCE has no entry for fall under the umbrella of upstream's tree; we
# record WHENCE itself for them (it carries the per-vendor terms).
if unlicensed:
    needed.add("linux-firmware-WHENCE")

licdirs = [os.path.join(src_root, "src/third_party", d, "licenses")
           for d in ("portage-stable", "chromiumos-overlay", "eclass-overlay")]
ours = os.path.join(overlay, "licenses")
os.makedirs(ours, exist_ok=True)
copied = []
for n in sorted(needed):
    if any(os.path.exists(os.path.join(d, n)) for d in licdirs):
        continue
    if n == "linux-firmware-WHENCE":
        src = os.path.join(upstream, "WHENCE")
    else:
        orig = {v: k for k, v in RENAME.items()}.get(n, n)
        src = next((s for s in (os.path.join(upstream, "LICENSES", orig),
                                os.path.join(upstream, orig)) if os.path.exists(s)), None)
        if src is None:
            sys.exit(f"license {n} not in the tree and not in upstream LICENSES/")
    shutil.copyfile(src, os.path.join(ours, n))
    copied.append(n)

text = open(ebuild).read()
block = ("# BEGIN GENERATED LICENSE (scripts/gen-firmware-list.py)\n"
         'LICENSE="\n' + "".join(f"\t{n}\n" for n in sorted(needed)) + '"\n'
         "# END GENERATED LICENSE")
new, n = re.subn(r"# BEGIN GENERATED LICENSE.*?# END GENERATED LICENSE", block, text, flags=re.S)
if n != 1:
    sys.exit(f"{ebuild}: GENERATED LICENSE markers not found")
open(ebuild, "w").write(new)
shutil.rmtree(stage)

by = {}
for p in missing:
    d = p.split("/")[0] if "/" in p else "(top)"
    by[d] = by.get(d, 0) + 1
print(f"selected {len(sel)} files; not available upstream: "
      + ", ".join(f"{k}:{v}" for k, v in sorted(by.items(), key=lambda x: -x[1])))
print(f"licenses: {len(needed)} ({', '.join(sorted(needed))})")
print(f"license texts added to overlay: {', '.join(copied) or 'none'}")
if unlicensed:
    print(f"no WHENCE entry ({len(unlicensed)}): {unlicensed[:5]}")
