#!/usr/bin/env python3
# Writes profile/package.use/zz-unified-google (the user profile, read before
# /etc/portage/package.use, so a user's line wins): for every package the image takes
# from Gentoo's tree, the USE flags Google built it with (the board's
# records), for the flags both ebuilds know. The OS's copies then behave as
# ChromeOS's did: Gentoo's profile defaults had turned on PulseAudio in
# alsa-plugins (cras and alsactl killed by their sandboxes) and turned off
# features ChromeOS uses (strongswan's EAP, iputils' tracepath, ffmpeg's
# VA-API...). A user who wants more rebuilds the package in their layer, as
# on any Gentoo. Our own choices stay in zz-unified-os, read after this.
#
# uf-google-use.py BOARD_VDB UNIFIED_VDB LIST > profile/package.use/zz-unified-google
# LIST: what the image takes from Gentoo's tree, one cat/pn a line: the
# image's records with repository "gentoo", less held-back.txt (the hook's
# own swap list misses what Portage pulls in for it, ffmpeg for one).
import os, re, sys

# Flags that aren't features: per-target expansions, profile and arch
# flags, and ones whose state follows the toolchain rather than the OS.
SKIP = re.compile(r"^(abi_|elibc_|kernel_|userland_|amd64$|x86$|python_|"
                  r"lua_|llvm_slot_|llvm_targets_|ruby_|cpu_flags_|l10n_|"
                  r"php_|perl_|qemu_|grub_|test$|doc$|static-libs$|"
                  r"split-usr$|debug$|nls$|selinux$|video_cards_|"
                  r"input_devices_)")

def index(vdb):
    out = {}
    for cat in os.listdir(vdb):
        for pf in os.listdir(f"{vdb}/{cat}"):
            m = re.match(r"(.+?)-\d", pf)
            if m:
                out[f"{cat}/{m.group(1)}"] = f"{vdb}/{cat}/{pf}"
    return out

def words(rec, name):
    try:
        with open(f"{rec}/{name}") as f:
            return f.read().split()
    except OSError:
        return []

board, unified = index(sys.argv[1]), index(sys.argv[2])
with open(sys.argv[3]) as f:
    swapped = {l.split()[0] for l in f if l.strip() and not l.startswith("#")}
print("# Generated by scripts/unified/uf-google-use.py; don't edit, see there.")
for cp in sorted(set(board) & set(unified) & swapped):
    g = unified[cp]
    if words(g, "repository") != ["gentoo"]:
        continue
    known = ({f.lstrip("+-") for f in words(board[cp], "IUSE")} &
             {f.lstrip("+-") for f in words(g, "IUSE")})
    known = {f for f in known if not SKIP.match(f)}
    # Every flag stated, on or off, not just the ones the root has
    # differently: the same file whatever the root has been rebuilt with.
    want = set(words(board[cp], "USE")) & known
    flags = [f if f in want else "-" + f for f in sorted(known)]
    if flags:
        print(cp, " ".join(flags))
